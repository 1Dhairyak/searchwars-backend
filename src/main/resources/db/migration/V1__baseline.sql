-- Baseline: the schema as Hibernate (ddl-auto=update) had built it in production
-- before Flyway was introduced. Production was baselined at version 1, so this
-- script only runs on fresh databases (local dev, tests).

create table game_sessions (
    id              varchar(255) not null,
    player_name     varchar(100),
    owner_key       varchar(80),
    current_item_id varchar(255),
    seen_item_ids   text,
    score           integer not null,
    status          varchar(20) not null check (status in ('ACTIVE','GAME_OVER','ABANDONED')),
    created_at      timestamp(6),
    updated_at      timestamp(6),
    primary key (id)
);

create table items (
    id            varchar(255) not null,
    title         varchar(200) not null unique,
    image_url     text not null,
    search_volume bigint not null check (search_volume >= 0),
    category      varchar(100),
    active        boolean not null,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    primary key (id)
);

create table leaderboard (
    id          varchar(255) not null,
    session_id  varchar(255) unique,
    player_name varchar(100) not null,
    score       integer not null check (score >= 0),
    achieved_at timestamp(6),
    primary key (id)
);

create table player_names (
    id           bigint generated by default as identity,
    name_key     varchar(20) not null unique,
    display_name varchar(20) not null,
    owner_key    varchar(80) not null unique,
    created_at   timestamp(6),
    primary key (id)
);

create table users (
    id            bigint generated by default as identity,
    email         varchar(255) not null unique,
    google_id     varchar(255),
    password_hash varchar(255),
    display_name  varchar(255),
    created_at    timestamp(6) with time zone,
    primary key (id)
);

create index idx_session_status          on game_sessions (status);
create index idx_session_player          on game_sessions (player_name);
create index idx_session_created_at      on game_sessions (created_at);
create index idx_session_owner           on game_sessions (owner_key);
create index idx_item_category           on items (category);
create index idx_item_active             on items (active);
create index idx_leaderboard_score       on leaderboard (score desc);
create index idx_leaderboard_player_name on leaderboard (player_name);
create index idx_leaderboard_achieved_at on leaderboard (achieved_at desc);
